let t=0, playing=false, raf=null, last=0, audio=null;

function render(v){
  t = v;
  if(fill) fill.style.width = (t/CFG.dur*100)+"%";
  if(tc)   tc.textContent = (t<10?"0":"") + t.toFixed(2);

  /* ONE clock. If a shot has been migrated to the GSAP engine, its timelines
     are scrubbed from here, so the animation and the scrub bar cannot disagree
     and scrubbing backwards is exact. Shots still on CSS keyframes ignore
     this — motion.js is only present on migrated shots. */
  if (window.M && M.seek) { try { M.seek(t, CFG.dur); } catch(e){} }
  else if (document.querySelector('script[src$="motion.js"]')) {
    /* motion.js is loaded but M is not reachable — the engine is dead and every
       tween in this shot is frozen. Surface it instead of rendering a still
       image that looks correct in any single frame. */
    if (!window.__motionWarned){ window.__motionWarned = 1;
      console.error('[] motion.js loaded but window.M is undefined — GSAP timelines will NOT play.'); }
  }

  /* The counter tween is owned by the beat that has the counter, via data
     attributes. It used to be hardcoded here at t=0.6-2.6s, which meant beat
     7 finished counting to 10 a full 1.4s BEFORE the word "ten" was spoken.
     Silent, because the number was right — just early. */
  const c = $("#counter");
  if(c && c.dataset.countTo){
    const from = +c.dataset.countStart, to = +c.dataset.countEnd, tgt = +c.dataset.countTo;
    const p = Math.max(0, Math.min(1, (t-from)/(to-from)));
    c.textContent = Math.round((1-Math.pow(1-p,3))*tgt);
  }
  if(nowBeat){
    let cur=null;
    for(const b of BEATS) if(t+CFG.offset >= b.t) cur=b;
    nowBeat.innerHTML = cur
      ? `▶ ${PARTLABEL} SHOT ${cur.n} &nbsp;${cur.name}<br>
         <span style="color:#39414F">global in ${(CFG.offset+t).toFixed(1)}s / ${TOTALOF}s</span>`
      : "&nbsp;";
  }
}

function loop(now){
  if(!playing) return;
  if(!last) last=now;
  const dt=(now-last)/1000; last=now;
  if(audio) return;
  render(Math.min(CFG.dur, t+dt));
  if(t>=CFG.dur){ stop(); return; }
  raf=requestAnimationFrame(loop);
}
function play(){
  if(t>=CFG.dur) restart();
  document.body.classList.add("playing");
  if(audio){ audio.currentTime=t; audio.play().catch(()=>{}); playing=true; }
  else { playing=true; last=0; raf=requestAnimationFrame(loop); }
  if($("#play")){ $("#play").innerHTML="&#10073;&#10073; PAUSE"; $("#play").classList.add("on"); }
}
function stop(){
  playing=false;
  document.body.classList.remove("playing");
  if(audio) audio.pause();
  if(raf) cancelAnimationFrame(raf);
  if($("#play")){ $("#play").innerHTML="&#9654; PLAY"; $("#play").classList.remove("on"); }
}
function restart(){
  document.body.classList.remove("playing");
  void stage.offsetWidth;
  if (window.M && M.reset) { try { M.reset(); } catch(e){} }
  render(0);
}
function replay(){ stop(); restart(); play(); }

